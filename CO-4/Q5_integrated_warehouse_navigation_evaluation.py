"""Task 5: Integrated warehouse simulation comparing Value Iteration, SARSA, Q-learning."""
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
ROWS=5; COLS=5; START=(0,0); GOAL=(4,4); WALLS={(1,1),(1,3),(2,3),(3,1)}
MOVES=[(-1,0),(1,0),(0,-1),(0,1)]; N=25; GAMMA=.95

def transition(s,a):
    r,c=divmod(s,COLS); dr,dc=MOVES[a]; nr,nc=r+dr,c+dc
    if not(0<=nr<ROWS and 0<=nc<COLS) or (nr,nc) in WALLS: return s,-5,False
    ns=nr*COLS+nc; done=(nr,nc)==GOAL
    return ns,(20 if done else -1),done

def value_iteration(theta=1e-5):
    V=np.zeros(N)
    while True:
        delta=0
        for s in range(N):
            if divmod(s,COLS)==GOAL or divmod(s,COLS) in WALLS: continue
            old=V[s]; V[s]=max((lambda z:z[1]+GAMMA*V[z[0]])(transition(s,a)) for a in range(4)); delta=max(delta,abs(old-V[s]))
        if delta<theta: break
    return V

def train(method,episodes=2500,seed=21):
    rng=np.random.default_rng(seed); Q=np.zeros((N,4)); ep_rewards=[]; steps=[]; successes=0; recent=[]
    for ep in range(episodes):
        s=0; total=0; count=0; eps=max(.03,.25*(1-ep/episodes))
        a=int(rng.integers(4)) if rng.random()<eps else int(np.argmax(Q[s]))
        for t in range(100):
            ns,r,done=transition(s,a); total+=r; count+=1
            if method=='SARSA':
                na=int(rng.integers(4)) if rng.random()<eps else int(np.argmax(Q[ns]))
                target=r+(0 if done else GAMMA*Q[ns,na])
            else:
                target=r+(0 if done else GAMMA*np.max(Q[ns])); na=None
            Q[s,a]+=.15*(target-Q[s,a]); s=ns
            if done: successes+=1; break
            a=na if method=='SARSA' else (int(rng.integers(4)) if rng.random()<eps else int(np.argmax(Q[s])))
        ep_rewards.append(total); steps.append(count); recent.append(int(done))
    return Q,np.array(ep_rewards),np.array(steps),float(np.mean(recent))

def path_from_q(Q):
    s=0; path=[(0,0)]; seen={s}
    for _ in range(50):
        ns,_,done=transition(s,int(np.argmax(Q[s])))
        if ns==s or ns in seen: break
        path.append(divmod(ns,COLS)); seen.add(ns); s=ns
        if done: break
    return path

if __name__=='__main__':
    out=Path(__file__).resolve().parent; results={}
    for method in ('SARSA','Q-Learning'):
        Q,R,S,success=train(method); results[method]=(R,S,success)
        print(f"{method}: avg reward(last 100)={R[-100:].mean():.2f}; avg steps(last 100)={S[-100:].mean():.2f}; success(last 100)={success:.1%}")
        print(method,"greedy route:",path_from_q(Q))
    V=value_iteration(); print("Value Iteration start-state value:",round(float(V[0]),3))
    print("Architecture: warehouse -> state observation -> epsilon-greedy action -> transition/reward -> learner update -> policy.")
    plt.figure();
    for name,(R,_,_) in results.items():
        window=100; avg=np.convolve(R,np.ones(window)/window,mode='valid'); plt.plot(avg,label=name)
    plt.xlabel('Episode'); plt.ylabel('Moving average reward (100 episodes)'); plt.title('Warehouse navigation learning performance'); plt.legend(); plt.tight_layout()
    graph=out/'Q5_learning_curve.png'; plt.savefig(graph,dpi=160); print('Saved graph:',graph)
    print("Note: Results are generated by this seeded simplified simulation; they are not measurements from a physical warehouse.")
